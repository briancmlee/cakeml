#!/usr/bin/env python3
"""
HOL cross-check for ffi_model_test.py: turns logged FFI calls into a HOL
script theory (ffiModelCheckScript.sml) that EVALuates the version-2 model
(socketV2FFI's ffi_sock_*2) on each logged call.  For each step it proves

    ffi_sock_X2 conf bytes s = SOME (FFIreturn out s')

where conf and bytes are the call's inputs, out is the REAL output of the C
function, s is the state before the call and s' the state after it, both as
computed by the Python transcription of the model (ModelV2).  So one EVAL
checks both the C (out) and the transcription (s, s') against the HOL model.

Each step is checked inside a handler: a step that does not evaluate to T
is reported (and counted) without stopping the build; the theory then
saves a summary theorem only if all steps were proved.

Usage: hol_check.py TRACE.jsonl [MAX_STEPS] > ffiModelCheckScript.sml
"""
import json, sys

def w8list(hexs):
    bs = bytes.fromhex(hexs)
    return "([" + ";".join(f"{b}w" for b in bs) + "]:word8 list)"

def w64(n):
    return f"({n}w:word64)"

def numlist(l):
    return "([" + ";".join(str(x) for x in l) + "]:num list)"

def conn(c):
    return (f"<| incoming := {w8list(c['incoming'])}; peer_closed := {'T' if c['peer_closed'] else 'F'};"
            f" outgoing := {w8list(c['outgoing'])} |>")

def arrival(a):
    if a[0] == "connect":
        return f"Connect2 {w64(a[1])}"
    if a[0] == "data":
        return f"Data2 {a[1]} {w8list(a[2])}"
    return f"Eof2 {a[1]}"

def state(m, future):
    lis = "[" + ";".join(f"({w64(l)}, {numlist(q)})" for (l, q) in m["listening"]) + "]"
    cls = "[" + ";".join(conn(c) for c in m["clients"]) + "]"
    ofs = "([" + ";".join(f"({w64(f)}, {j})" for (f, j) in m["open_fds"]) + "]:(word64 # num) list)"
    res = "([" + ";".join(w64(f) for f in m["reserved"]) + "]:word64 list)"
    return (f"(<| listening := {lis}; clients := ({cls}:conn list); open_fds := {ofs};"
            f" reserved := {res}; future := {future} |> : sockets2)")

def future(step):
    if step is None:
        return "(LNIL : arrival2 list llist)"
    return "(fromList [[" + ";".join(arrival(a) for a in step) + "]] : arrival2 list llist)"

FN = {"poll": "ffi_sock_poll2", "accept": "ffi_sock_accept2", "read": "ffi_sock_read2",
      "write": "ffi_sock_write2", "close": "ffi_sock_close2"}

def main():
    path = sys.argv[1]
    limit = int(sys.argv[2]) if len(sys.argv) > 2 else 10 ** 9
    entries = [json.loads(l) for l in open(path)][:limit]
    out = []
    out.append("""(*
  GENERATED by hol_check.py from a trace of ffi_model_test.py: do not edit.
  EVALuates the version-2 socket model on each logged call of the real
  socket_ffi.c (see async/design/29-ffi-model-test.md).
*)
Theory ffiModelCheck
Ancestors
  socketV2FFI ffiModelTest llist
Libs
  preamble

val ok = ref 0;
val bad = ref ([] : string list);

fun check name goal used_f =
  let
    val tac =
      case used_f of
        NONE => EVAL_TAC
      | SOME (used, f) =>
          let val lf = prove (mk_eq (mk_comb (prim_mk_const {Thy = "socketV2FFI", Name = "lowest_free"}, used),
                                     wordsSyntax.mk_n2w (numSyntax.term_of_int f, ``:64``)),
                              irule lowest_free_intro >> EVAL_TAC)
          in simp[ffi_sock_accept2_def, sock_accept2_def, used_fds_def, lf] >> EVAL_TAC end
  in
    (prove (goal, tac); ok := !ok + 1)
    handle e => (bad := name :: !bad;
                 print ("HOL CHECK FAILED: " ^ name ^ "\\n"))
  end;
""")
    for e in entries:
        if e["real"] is None:
            continue
        name = f"seed{e['seed']}_step{e['n']}_{e['op']}"
        s0 = state(e["before"], future(e["step"]) if e["op"] == "poll" else "(LNIL : arrival2 list llist)")
        s1 = state(e["after"], "(LNIL : arrival2 list llist)")
        goal = (f"{FN[e['op']]} {w8list(e['conf'])} {w8list(e['bytes_in'])} {s0} = "
                f"SOME (FFIreturn {w8list(e['real'])} {s1})")
        used_f = "NONE"
        real = bytes.fromhex(e["real"])
        if e["op"] == "accept" and real[0] == 1:
            m = e["before"]
            used = m["reserved"] + [l for (l, _) in m["listening"]] + [f for (f, _) in m["open_fds"]]
            f = int.from_bytes(real[1:9], "big")
            used_f = f"SOME (``([{';'.join(w64(u) for u in used)}]:word64 list)``, {f})"
        out.append(f'val _ = check "{name}"\n  ``{goal}``\n  ({used_f});')
    out.append("""
val _ = print ("HOL CHECK: " ^ Int.toString (!ok) ^ " steps proved, " ^
               Int.toString (length (!bad)) ^ " failed\\n");
val _ = if null (!bad) then () else raise Fail "HOL check: some steps failed";
""")
    print("\n".join(out))

if __name__ == "__main__":
    main()
